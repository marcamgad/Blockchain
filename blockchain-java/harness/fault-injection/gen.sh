#!/usr/bin/env bash
# [O-2] Generates a throw-away N-validator harness network: fresh random keys (KeygenTool, no seed),
# a random CA seed and one random storage key per node, plus docker-compose.N.yml.
#   harness/fault-injection/gen.sh 4      (or 7)
set -euo pipefail
N="${1:?usage: gen.sh <validators>}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
cd "$ROOT"
ENV="$HERE/.env.$N"; COMPOSE="$HERE/docker-compose.$N.yml"; ADDR="$HERE/.addresses.$N"
# keys are generated once; the compose file (no secrets, only ${...} references) is rewritten each
# time so harness changes reach existing networks. Delete .env.N to get new keys.
if [[ ! -e "$ENV" ]]; then
[[ -f cp.txt ]] || mvn -q -DskipTests dependency:build-classpath -Dmdep.outputFile=cp.txt
mvn -q -DskipTests compile
SEP=":"; case "$(uname -s)" in MINGW*|MSYS*|CYGWIN*) SEP=";" ;; esac
RAW="$(mktemp)"; trap 'rm -f "$RAW"' EXIT
java -cp "target/classes${SEP}$(cat cp.txt)" com.hybrid.blockchain.tools.KeygenTool "$N" > "$RAW" 2>/dev/null
rand_hex() { if command -v openssl >/dev/null; then openssl rand -hex "$1"; else head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'; fi; }

umask 077
{
  echo "# throw-away harness network, $N validators. Not for any real deployment."
  echo "NETWORK_CA_SEED=$(rand_hex 32)"
  echo "JWT_SECRET=$(rand_hex 32)"
  echo "VALIDATOR_PUBKEYS=$(grep '^VALIDATOR_PUBKEYS=' "$RAW" | cut -d= -f2)"
  for i in $(seq 1 "$N"); do
    echo "V${i}_KEY=$(grep "^NODE_${i}_PRIVATE_KEY=" "$RAW" | cut -d= -f2)"
    echo "V${i}_AES=$(rand_hex 16)"
  done
} > "$ENV"
: > "$ADDR"
for i in $(seq 1 "$N"); do echo "hc-v$i $(grep "^NODE_${i}_ADDRESS=" "$RAW" | cut -d= -f2)" >> "$ADDR"; done
echo "wrote $ENV (mode 600) and $ADDR"
fi

{
  echo "# generated by gen.sh: $N validators on ONE host (simulated network)"
  echo "name: hc-harness-$N"
  echo "networks: {hcnet: {ipam: {config: [{subnet: 172.28.0.0/24}]}}}"
  # one named volume per node: a container recreated with a different environment (clock-skew)
  # keeps its chain instead of starting again from genesis
  echo "volumes: {$(for i in $(seq 1 "$N"); do printf 'v%s-data: {}%s' "$i" "$([[ $i -lt $N ]] && echo ', ')"; done)}"
  echo "services:"
  for i in $(seq 1 "$N"); do
    seed=$([[ $i -eq 1 ]] && echo true || echo false)
    cat <<EOF
  v$i:
    image: hybridchain-harness:local
    container_name: hc-v$i
    hostname: v$i
    environment:
      NODE_PRIVATE_KEY: \${V${i}_KEY}
      STORAGE_AES_KEY: \${V${i}_AES}
      VALIDATOR_PUBKEYS: \${VALIDATOR_PUBKEYS}
      NETWORK_CA_SEED: \${NETWORK_CA_SEED}
      JWT_SECRET: \${JWT_SECRET}
      NODE_ROLE: VALIDATOR
      NODE_ID: v$i
      IS_SEED: "$seed"
      SEED_PEER: "$([[ $i -eq 1 ]] && echo '' || echo 'v1:6001')"
      P2P_PORT: "6001"
      API_PORT: "8080"
      STORAGE_PATH: /app/data
      FAKETIME: \${V${i}_FAKETIME:-}
      LD_PRELOAD: \${V${i}_PRELOAD:-}
      FAKETIME_DONT_FAKE_MONOTONIC: "1"
    volumes: ["v$i-data:/app/data"]
    ports: ["$((18080 + i)):8080", "$((15683 + i)):5683/udp"]
    networks: {hcnet: {ipv4_address: 172.28.0.$((10 + i))}}
EOF
  done
} > "$COMPOSE"
echo "wrote $COMPOSE"

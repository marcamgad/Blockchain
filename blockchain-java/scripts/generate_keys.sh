#!/usr/bin/env bash
# Generates fresh key material for ONE HybridChain network: 20 node keys, the validator public-key
# list, a storage AES key and the network CA seed. [O-3] This script and KeygenTool are the only
# supported sources of keys (docs/KEY_ROTATION.md).
#
#   scripts/generate_keys.sh [OUT_ENV]                 random keys (use this)
#   scripts/generate_keys.sh --test-seed SEED [OUT]    reproducible TEST keys; anyone who knows SEED
#                                                      knows every key. Never for a real network.
#
# The output holds private keys: it is created with mode 600, is never overwritten, and must never
# be committed (.gitignore covers .env and .env.*).
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

SEED_ARGS=()
if [[ "${1:-}" == "--test-seed" ]]; then
  [[ -n "${2:-}" ]] || { echo "--test-seed needs a value" >&2; exit 2; }
  SEED_ARGS=("$2")
  echo "WARNING: deterministic TEST keys from a seed. Anyone who knows the seed knows every key." >&2
  shift 2
fi
OUT_ENV="${1:-.env.network}"
COUNT=20

if [[ -e "$OUT_ENV" ]]; then
  echo "Refusing to overwrite $OUT_ENV (it may hold live keys). Choose another path." >&2
  exit 1
fi

rand_hex() {   # rand_hex <bytes>: hex from the OS CSPRNG
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex "$1"
  else
    head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'
  fi
}

if [[ ! -f cp.txt ]]; then
  mvn -q -DskipTests dependency:build-classpath -Dmdep.outputFile=cp.txt
fi
mvn -q -DskipTests compile

KEYS_RAW="$(mktemp)"
trap 'rm -f "$KEYS_RAW"' EXIT
chmod 600 "$KEYS_RAW"

# no seed argument -> KeygenTool uses 32 bytes from SecureRandom
CP_SEP=":"; case "$(uname -s)" in MINGW*|MSYS*|CYGWIN*) CP_SEP=";" ;; esac   # Java on Windows uses ';'
java -cp "target/classes${CP_SEP}$(cat cp.txt)" com.hybrid.blockchain.tools.KeygenTool "$COUNT" "${SEED_ARGS[@]}" > "$KEYS_RAW"

declare -A PRIV
declare -A PUB
while IFS='=' read -r key value; do
  case "$key" in
    NODE_*_PRIVATE_KEY) idx="${key#NODE_}"; PRIV["${idx%_PRIVATE_KEY}"]="$value" ;;
    NODE_*_PUBLIC_KEY)  idx="${key#NODE_}"; PUB["${idx%_PUBLIC_KEY}"]="$value" ;;
  esac
done < "$KEYS_RAW"

for i in $(seq 1 "$COUNT"); do
  [[ -n "${PRIV[$i]:-}" && -n "${PUB[$i]:-}" ]] || { echo "Missing key material for index $i" >&2; exit 1; }
done

STORAGE_AES_KEY="$(rand_hex 16)"
NETWORK_CA_SEED="$(rand_hex 32)"
JWT_SECRET="$(rand_hex 32)"   # REST API token key; required outside DEBUG (HC-052)
VALIDATOR_PUBKEYS="${PUB[2]},${PUB[3]},${PUB[4]},${PUB[5]}"

umask 077
{
  echo "# Generated by scripts/generate_keys.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). SECRET: never commit."
  [[ ${#SEED_ARGS[@]} -gt 0 ]] && echo "# TEST KEYS from a seed: not for any real network."
  echo "STORAGE_AES_KEY=$STORAGE_AES_KEY"
  echo "NETWORK_CA_SEED=$NETWORK_CA_SEED"
  echo "JWT_SECRET=$JWT_SECRET"
  echo
  echo "NODE_SEED_PRIVATE_KEY=${PRIV[1]}"
  for v in 1 2 3 4; do echo "NODE_VALIDATOR_${v}_PRIVATE_KEY=${PRIV[$((v + 1))]}"; done
  echo
  for p in $(seq 1 15); do echo "NODE_PEER_${p}_PRIVATE_KEY=${PRIV[$((p + 5))]}"; done
  echo
  echo "VALIDATOR_PUBKEYS=$VALIDATOR_PUBKEYS"
} > "$OUT_ENV"
chmod 600 "$OUT_ENV"

echo "Wrote $OUT_ENV (mode 600). Public validator keys: $VALIDATOR_PUBKEYS"
